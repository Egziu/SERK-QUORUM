export const PROVIDERS = Object.freeze([
  {id:'openai',name:'ChatGPT',role:'Architect',env:'OPENAI'},
  {id:'anthropic',name:'Claude',role:'Builder',env:'ANTHROPIC'},
  {id:'gemini',name:'Gemini',role:'Scientist',env:'GEMINI'},
  {id:'xai',name:'Grok',role:'Challenger',env:'XAI'}
]);
export const TASKS = Object.freeze({
  planning:'Prepare a project plan with milestones, dependencies and assumptions.',
  requirements:'Draft product requirements with user needs and acceptance criteria.',
  research:'Summarize supplied non-sensitive research material; distinguish facts and uncertainty.',
  review:'Review a business or product proposal for clarity, tradeoffs and open questions.'
});
export function validate(body) {
  if (!body || typeof body !== 'object' || Array.isArray(body)) throw new Error('Invalid request');
  const {provider,task,prompt,live=false}=body;
  if (!PROVIDERS.some(p=>p.id===provider)) throw new Error('Unknown provider');
  if (!Object.hasOwn(TASKS,task)) throw new Error('Unknown task');
  if (typeof prompt!=='string'||!prompt.trim()||prompt.length>4000) throw new Error('Brief must be 1–4000 characters');
  if (typeof live!=='boolean') throw new Error('Invalid live flag');
  return {provider,task,prompt:prompt.trim(),live};
}
export function demo({provider,task}) {
  const p=PROVIDERS.find(x=>x.id===provider);
  const views={
    openai:'Define the outcome, stakeholders and boundaries. Document architectural options and the decision criteria.',
    anthropic:'Break the work into small deliverables. Specify completion criteria, dependencies and a review checklist.',
    gemini:'Identify missing evidence, research questions and validation methods. Record assumptions and sources.',
    xai:'Challenge the assumptions, consider alternatives and record the strongest counterarguments.'
  };
  return {provider,mode:'demo',model:'fixture',text:'Illustrative response — not generated by a live AI.\n\n'+TASKS[task]+'\n\n'+views[provider]+'\n\nNext: confirm the brief and nominate a human reviewer.',usage:null};
}
export function configured(p,env) {
  return Boolean(env.QUORUM_LIVE==='1'&&env.QUORUM_ACCESS_TOKEN?.length>=32&&env[p.env+'_API_KEY']&&env[p.env+'_MODEL']);
}
export function publicProviders(env) {
  return PROVIDERS.map(p=>({id:p.id,name:p.name,role:p.role,configured:configured(p,env)}));
}
